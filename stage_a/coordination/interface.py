"""Coordination port. Acceptance = a successful conditional compare-and-swap of the namespace HEAD.
This is the same 3-method port the Tracker claim layer already uses, plus epoch acquisition."""
from typing import Protocol, List
from tracker_component.journal_port import Head, JournalRecord

class FencedJournal(Protocol):
    def acquire_epoch(self) -> int: ...
    def head(self) -> Head: ...
    def append(self, expected_head: Head, kind: str, body: dict) -> JournalRecord: ...
    def read_from(self, seq: int) -> List[JournalRecord]: ...
